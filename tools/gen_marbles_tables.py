def array(src: str, name: str) -> str:
    """Return the body (between braces) of `const float NAME[] = { ... };`."""
    m = re.search(r"const float %s\[\] = \{(.*?)\};" % re.escape(name), src, re.S)
    if not m:
        sys.exit(f"table {name} not found")
    return m.group(1)


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    euro, stm, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    res = (euro / "marbles" / "resources.cc").read_text()
    units = (stm / "dsp" / "units.cc").read_text()

    m = re.search(r"const float\* distributions_table\[\] = \{(.*?)\};", res, re.S)
    if not m:
        sys.exit("distributions_table not found")
    dist_names = re.findall(r"dist_icdf_\d+_\d+", m.group(1))
    unique = sorted(set(dist_names) | {"dist_icdf_4_3"})

    parts = [HEADER]
    for name in ["lut_logit", "lut_raised_cosine"] + unique:
        parts.append(f"\nconst float tm_{name}[] = {{{array(res, name)}}};\n")
    for name in ["lut_pitch_ratio_high", "lut_pitch_ratio_low"]:
        parts.append(f"\nconst float tm_{name}[] = {{{array(units, name)}}};\n")
    parts.append("\nconst float *const tm_distributions_table[] = {\n")
    parts.extend(f"    tm_{n},\n" for n in dist_names)
    parts.append("};\n")
    out.write_text("".join(parts))
    print(f"marbles tables: {len(unique)} distributions, {len(dist_names)} table cells -> {out}")


if __name__ == "__main__":
    main()
